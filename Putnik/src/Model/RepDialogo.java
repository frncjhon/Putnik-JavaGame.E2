    // Seleciona a cena correta a partir de capítulo e cena (null se não existir).
    public static Dialogo[] obterCena(int capitulo, int cena) {

        return switch (capitulo) {

            case 1 -> switch (cena) {
                case 1 -> cap1cen1;
                case 2 -> cap1cen2;
                case 3 -> cap1cen3;
                case 4 -> cap1cen4;
                default -> null;
            };

            case 2 -> switch (cena) {
                case 1 -> cap2cen1;
                case 2 -> cap2cen2;
                case 3 -> cap2cen3;
                case 4 -> cap2cen4;
                default -> null;
            };

            case 3 -> switch (cena) {
                case 1 -> cap3cen1;
                case 2 -> cap3cen2;
                case 3 -> cap3cen3;
                case 4 -> cap3cen4;
                default -> null;
            };

            case 4 -> switch (cena) {
                case 1 -> cap4cen1;
                case 2 -> cap4cen2;
                case 3 -> cap4cen3;
                case 4 -> cap4cen4;
                default -> null;
            };

            case 5 -> switch (cena) {
                case 1 -> cap5cen1;
                case 2 -> cap5cen2;
                case 3 -> cap5cen3;
                case 4 -> cap5cen4;
                default -> null;
            };

            // Capítulo 6: finais.
            case 6 -> switch (cena) {
                case 1 -> final1;
                case 2 -> final2;
                case 3 -> final3;
                default -> null;
            };

            // Capítulo 7: conteúdo extra.
            case 7 -> switch (cena) {
                case 1 -> Extra;
                default -> null;
            };

            default -> null;
        };
    }
